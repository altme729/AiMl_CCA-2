import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score, classification_report

# 1. Load the dataset generated by the admin
input_filename = "ml_input_data.xlsx"
try:
    df = pd.read_excel(input_filename)
    print(f"Successfully loaded '{input_filename}'\n")
except FileNotFoundError:
    print(f"Error: '{input_filename}' not found. Please run the admin script first.")
    exit()

# 2. Prepare the data for Machine Learning
# Features (X) and Target Label (y)
X = df[['Credit_Score', 'Income_k']]
y = df['Actual_Risk']

# 3. Split the data into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)

# 4. Initialize and train the Machine Learning model (Decision Tree)
model = DecisionTreeClassifier(random_state=42)
model.fit(X_train, y_train)

# 5. Make predictions and evaluate the model
predictions = model.predict(X_test)
accuracy = accuracy_score(y_test, predictions)

print("--- Model Evaluation ---")
print(f"Accuracy: {accuracy * 100:.2f}%\n")
print("Classification Report:")
print(classification_report(y_test, predictions, zero_division=0))

# 6. Test the model with a new, unseen customer
new_customer = pd.DataFrame({'Credit_Score': [620], 'Income_k': [35]})
new_prediction = model.predict(new_customer)

print("--- Prediction for New Customer ---")
print(f"Customer Data -> Credit Score: 620 | Income: 35k")
print(f"Predicted Risk: {new_prediction[0]}")
